import turtle
screen = turtle.Screen()
screen.setup(420, 320)
my_turtle = turtle.Turtle()
my_turtle.shape("turtle")
my_turtle.color("lightblue")
my_turtle.shapesize(2)
my_turtle.pensize(4)
my_turtle.penup()
my_turtle.goto(-90, 30)
my_turtle.pendown()
my_turtle.begin_fill()
for i in range(5):
    my_turtle.forward(200)
    my_turtle.right(144)
my_turtle.end_fill()
my_turtle.penup()
my_turtle.goto(80, -144)
my_turtle.color("olive")
my_turtle.write("تمام شد", font=("arial", 20))
my_turtle.ht()
turtle.done()
